# GPT 翻译函数
# ─────────────────────────────────────────────
def gpt_translate(text: str) -> str:
    prompt = (
        "将以下俄语游戏文本翻译成简体中文。\n"
        "规则：\n"
        "- 保留所有 <color=xxx>…</color> 标签原样\n"
        "- 保留所有 {0} {1} {2} 占位符\n"
        "- 保留 | 换行符\n"
        "- 人名用标准中文音译\n"
        "- 只输出翻译结果，不加解释\n\n"
        f"{text}"
    )
    for attempt in range(3):
        try:
            resp = requests.post(
                URL,
                headers={"Authorization": f"Bearer {KEY}", "Content-Type": "application/json"},
                json={"model": MODEL, "messages": [{"role": "user", "content": prompt}], "temperature": 0.3},
                timeout=90,
            )
            resp.raise_for_status()
            return resp.json()["choices"][0]["message"]["content"].strip()
        except Exception as e:
            if attempt < 2:
                print(f"  ⚠ 第{attempt+1}次失败: {e}，重试…")
                time.sleep(3)
            else:
                raise

# ─────────────────────────────────────────────
# 主流程
# ─────────────────────────────────────────────
def load(name: str) -> tuple[str, list[str], dict]:
    for fname in os.listdir(BASE):
        if not fname.endswith(".json"): continue
        path = os.path.join(BASE, fname)
        with open(path) as f: d = json.load(f)
        if d.get("m_Name") == name:
            return path, (d.get("m_Script","") or "").splitlines(), d
    raise FileNotFoundError(name)

def save(path: str, d: dict, lines: list[str]):
    d["m_Script"] = "\n".join(lines)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=4)

